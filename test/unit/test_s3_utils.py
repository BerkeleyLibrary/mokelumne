@patch("mokelumne.util.s3_utils.S3Hook")
def test_download_single_s3_file_success(mock_s3_hook, tmp_path):
    """Should correctly invoke S3Hook download and return the local path."""
    mock_hook_instance = MagicMock()
    mock_s3_hook.return_value = mock_hook_instance
    
    dest_dir = str(tmp_path)
    file_key = "reports/daily_report.docx"
    expected_output_path = os.path.join(dest_dir, "daily_report.docx")

    result = download_single_s3_file(
        file_key=file_key,
        bucket_name="my-bucket",
        dest_dir=dest_dir,
        conn_id="custom_conn" # Kept custom string
    )
    
    assert result == expected_output_path
    mock_s3_hook.assert_called_once_with(
        aws_conn_id="custom_conn",
        config={"connect_timeout": 60, "read_timeout": 300}
    )
    mock_hook_instance.download_file.assert_called_once_with(
        key=file_key,
        bucket_name="my-bucket",
        local_path=dest_dir,
        preserve_file_name=True,
        use_autogenerated_subdir=False
    )


@patch("mokelumne.util.s3_utils.S3Hook")
@patch("mokelumne.util.s3_utils.os.path.exists")
def test_download_single_s3_file_failure_with_existing_file(mock_exists, mock_s3_hook, tmp_path):
    """Should wrap exception in a RuntimeError and check if local file exists on failure."""
    mock_hook_instance = MagicMock()
    mock_hook_instance.download_file.side_effect = Exception("S3 Network Timeout")
    mock_s3_hook.return_value = mock_hook_instance
    mock_exists.return_value = True

    with pytest.raises(RuntimeError) as exc_info:
        download_single_s3_file(
            file_key="path/to/data.json",
            bucket_name="my-bucket",
            dest_dir=str(tmp_path),
            conn_id="aws_s3_conn" 
        )
        
    assert "Failed to download path/to/data.json: S3 Network Timeout" in str(exc_info.value)
    mock_exists.assert_called_once_with(os.path.join(str(tmp_path), "data.json"))
